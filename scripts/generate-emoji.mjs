#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const revision = 'ee6e06c648e85d601756b573d356327d4e51031d';
const checksum = 'b174ae2aeb321b52f64adb9ff412f966a7f338839d780784dd15dcad702c2dd6';
const source = new URL('../kotmark-ext-emoji/data/gemoji.json', import.meta.url);
const output = new URL('../kotmark-ext-emoji/src/ext/emoji/internal/generated/GemojiAliases.kt', import.meta.url);
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: generate-emoji.mjs [--check]');
const bytes = readFileSync(source);
if (createHash('sha256').update(bytes).digest('hex') !== checksum) throw new Error('gemoji.json checksum mismatch');
const entries = JSON.parse(bytes.toString('utf8'));
const aliases = new Map();
for (const entry of entries) {
  if (typeof entry.emoji !== 'string' || !entry.emoji || /[\r\n]/.test(entry.emoji)) throw new Error('Invalid Unicode emoji');
  for (const alias of entry.aliases) {
    if (!/^[a-z0-9_+-]+$/.test(alias) || aliases.has(alias)) throw new Error('Invalid or duplicate alias: ' + alias);
    aliases.set(alias, entry.emoji);
  }
}
if (entries.length !== 1870 || aliases.size !== 1913) throw new Error('Unexpected dictionary counts');
const sorted = [...aliases].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
const parts = [];
for (let i = 0; i < sorted.length; i += 256) parts.push(sorted.slice(i, i + 256));
const literal = text => JSON.stringify(text).replaceAll('$', '\\$');
const lines = [
  '// Generated by node scripts/generate-emoji.mjs. Do not edit.',
  '// Source: https://github.com/github/gemoji/blob/' + revision + '/db/emoji.json',
  '// SHA-256: ' + checksum,
  '// Copyright (c) 2019 GitHub, Inc. MIT license: resources/META-INF/LICENSE-gemoji.txt.',
  'package io.heapy.kotmark.ext.emoji.internal.generated',
  '',
  'internal val gemojiAliases: Map<String, String> by lazy {',
  '    buildMap(' + aliases.size + ') {',
  ...parts.map((_, i) => '        addAliases' + i + '()'),
  '    }',
  '}',
];
for (const [index, part] of parts.entries()) {
  lines.push('', 'private fun MutableMap<String, String>.addAliases' + index + '() {');
  for (const [alias, emoji] of part) lines.push('    put(' + literal(alias) + ', ' + literal(emoji) + ')');
  lines.push('}');
}
const generated = lines.join('\n') + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Generated emoji table is out of date');
} else {
  mkdirSync(dirname(fileURLToPath(output)), { recursive: true });
  writeFileSync(output, generated);
}
console.log('Emoji dictionary: ' + entries.length + ' entries, ' + aliases.size + ' aliases (' + (process.argv.includes('--check') ? 'verified' : 'generated') + ')');
