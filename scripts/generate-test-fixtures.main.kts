#!/usr/bin/env kotlinr

// Rebuild common Kotlin fixture text from the committed, checksum-pinned corpora.
// Run from the project root: kotlinr scripts/generate-test-fixtures.main.kts [--check]
import java.nio.file.Path
import java.security.MessageDigest
import kotlin.io.path.*

require(args.isEmpty() || args.contentEquals(arrayOf("--check"))) { "Usage: generate-test-fixtures.main.kts [--check]" }
val checkOnly = args.isNotEmpty()
val root = Path.of("").toAbsolutePath().normalize()
val upstream = root.resolve("test-fixtures/resources/upstream")
val output = root.resolve("test-fixtures/src/testfixtures/generated")
val manifest = upstream.resolve("SHA256SUMS").readText()
val fixtures = manifest.lineSequence().filter { it.isNotBlank() }.map { line ->
    val (checksum, name) = line.split("  ", limit = 2)
    val bytes = upstream.resolve(name).readBytes()
    check(MessageDigest.getInstance("SHA-256").digest(bytes).toHexString() == checksum) {
        "Fixture checksum mismatch: $name"
    }
    val text = bytes.decodeToString(throwOnInvalidSequence = true)
    check(text.encodeToByteArray().contentEquals(bytes)) { "UTF-8 round trip failed: $name" }
    name to text
}.toList()

fun literal(value: String): String = buildString {
    append('"')
    for (c in value) when (c) {
        '\\' -> append("\\\\")
        '"' -> append("\\\"")
        '$' -> append("\\$")
        '\n' -> append("\\n")
        '\r' -> append("\\r")
        '\t' -> append("\\t")
        else -> if (c in ' '..'~') append(c) else append("\\u" + c.code.toString(16).padStart(4, '0'))
    }
    append('"')
}

val header = """
    // Generated by scripts/generate-test-fixtures.main.kts. Do not edit.
    // Upstream content and notices: UPSTREAM.md. Original fixture bytes are unchanged.
    package io.heapy.kotmark.testfixtures.generated

""".trimIndent()
val files = linkedMapOf<String, String>()
fixtures.forEachIndexed { index, (name, text) ->
    files["Corpus$index.kt"] = buildString {
        appendLine(header)
        appendLine("// Source: $name")
        appendLine("internal fun corpus$index(): String = buildString(${text.length}) {")
        // Keep each constant well below the JVM modified-UTF-8 limit. Separate
        // append calls prevent the compiler folding the whole corpus into one constant.
        for (chunk in text.chunked(8_000)) appendLine("    append(${literal(chunk)})")
        appendLine("}")
    }
}
files["EmbeddedFixtures.kt"] = buildString {
    appendLine(header)
    appendLine("internal fun embeddedFixture(path: String): String = when (path) {")
    fixtures.forEachIndexed { index, (name, _) -> appendLine("    ${literal(name)} -> corpus$index()") }
    appendLine("    else -> error(\"Unknown bundled test fixture: \$path\")")
    appendLine("}")
}
if (!checkOnly) output.createDirectories()
val expectedFiles = files.keys.toSet()
val actualFiles = if (output.exists()) output.listDirectoryEntries("*.kt").map { it.name }.toSet() else emptySet()
check((actualFiles - expectedFiles).isEmpty()) { "Unexpected generated files: ${actualFiles - expectedFiles}" }
for ((name, content) in files) {
    val file = output.resolve(name)
    if (checkOnly) check(file.exists() && file.readText() == content) { "Regenerate fixture source: $file" }
    else file.writeText(content)
}
println("${if (checkOnly) "Verified" else "Generated"} ${fixtures.size} complete corpora (${fixtures.sumOf { it.second.length }} UTF-16 code units).")
