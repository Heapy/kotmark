    fun isLetter(codePoint: Int): Boolean = when (category(codePoint)) {
        CharCategory.UPPERCASE_LETTER, CharCategory.LOWERCASE_LETTER,
        CharCategory.TITLECASE_LETTER, CharCategory.MODIFIER_LETTER,
        CharCategory.OTHER_LETTER -> true
        else -> false
    }

    fun category(codePoint: Int): CharCategory {
        if (codePoint in 0..0xFFFF) return codePoint.toChar().category
        var low = 0
        var high = SUPPLEMENTARY_RANGES.size / 3 - 1
        while (low <= high) {
            val middle = (low + high) ushr 1
            val offset = middle * 3
            when {
                codePoint < SUPPLEMENTARY_RANGES[offset] -> high = middle - 1
                codePoint > SUPPLEMENTARY_RANGES[offset + 1] -> low = middle + 1
                else -> return categoriesByValue[SUPPLEMENTARY_RANGES[offset + 2]]
            }
        }
        return CharCategory.UNASSIGNED
    }

